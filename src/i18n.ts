/** 获取翻译文本，支持 {key} 占位符替换 */
export function t(key: string, lang: Language, params?: Record<string, string>): string {
  const map = strings[lang] ?? strings["en"];
  let text = map[key];
  if (text === undefined) {
    text = strings["en"][key] ?? key;
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}
